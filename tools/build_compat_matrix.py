"""1.10.0 (plan 3.3): the compatibility matrix, generated from data.

docs/compat/compat.json holds one record per report: game, backend (DLSS-G,
XeMFG DLSS-G, once XMX, XeMFG), API, GPU, Streamline and frame generation file versions when
known, the result (Working, Partially working, Not working, Untested), notes,
the source and its date. The README's tested-game tables are imported once
with --import-readme and are then one source among the others.

  python tools/build_compat_matrix.py --import-readme   # seed compat.json from README.md
  python tools/build_compat_matrix.py                   # write docs/compat/matrix.md
  python tools/build_compat_matrix.py --check           # fail if matrix.md is stale

A support report (the panel's Copy report) can be turned into a record:
  python tools/build_compat_matrix.py --from-report report.txt --game "Keeper" --result "Not working" --source "Calledme_kev"
"""
import datetime
import json
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
DATA = os.path.join(ROOT, "docs", "compat", "compat.json")
MATRIX = os.path.join(ROOT, "docs", "compat", "matrix.md")
RESULTS = ["Working", "Partially working", "Not working", "Untested"]
FIELDS = ["game", "backend", "api", "gpu", "streamline", "provider", "result", "notes", "source", "date"]


def load():
    if not os.path.exists(DATA):
        return []
    return json.load(open(DATA, encoding="utf-8"))["records"]


def save(records):
    os.makedirs(os.path.dirname(DATA), exist_ok=True)
    payload = {"schema": 1, "fields": FIELDS, "results": RESULTS, "records": records}
    open(DATA, "w", encoding="utf-8", newline="\n").write(json.dumps(payload, ensure_ascii=False, indent=1) + "\n")


def normalize_result(text):
    t = text.strip().lower()
    if not t or t in ("-", "?"):
        return "Untested"
    if t.startswith("working") or t in ("works", "ok", "yes"):
        return "Working"
    if t.startswith("partial"):
        return "Partially working"
    if t.startswith("not") or t.startswith("no") or "broken" in t or "crash" in t:
        return "Not working"
    return "Working" if "working" in t else "Untested"


def import_readme():
    text = open(os.path.join(ROOT, "README.md"), encoding="utf-8").read()
    records = []
    dlssg = text[text.index("### DLSS-G backend tested games"):text.index("### XeMFG backend tested games")]
    for row in re.findall(r"^\| ([^|]+?) \| ([^|]*?) \|$", dlssg, re.M):
        game, status = row
        if game in ("Game", "---") or game.startswith("May work"):
            continue
        records.append({"game": game, "backend": "DLSS-G", "api": "DX12", "gpu": "RTX 40", "streamline": "", "provider": "",
                        "result": normalize_result(status), "notes": "" if normalize_result(status) != "Untested" else status,
                        "source": "README (before 1.10.0)", "date": ""})
    xemfg = text[text.index("### XeMFG backend tested games"):]
    xemfg = xemfg[:xemfg.index("\n## ")]
    for cells in re.findall(r"^\| ([^|]+?) \| ([^|]*?) \| ([^|]*?) \| ([^|]*?) \| ([^|]*?) \|$", xemfg, re.M):
        game, api, cuda, xmx, notes = (c.strip() for c in cells)
        if game in ("Game", "---"):
            continue
        for backend, status in (("XeMFG", cuda), ("XeMFG DLSS-G", xmx)):
            if not status:
                continue
            records.append({"game": game, "backend": backend, "api": api, "gpu": "RTX 40", "streamline": "", "provider": "",
                            "result": normalize_result(status), "notes": notes if backend == "XeMFG" else status if normalize_result(status) == "Untested" else "",
                            "source": "README (before 1.10.0)", "date": ""})
    return records


def from_report(path, game, result, source):
    fields = {}
    for line in open(path, encoding="utf-8", errors="replace").read().splitlines():
        if "=" in line:
            k, v = line.split("=", 1)
            fields.setdefault(k.strip(), v.strip())
    backend = fields.get("method", "")
    return {"game": game, "backend": backend, "api": fields.get("renderer", ""), "gpu": fields.get("gpu", ""),
            "streamline": fields.get("chain_streamline", ""), "provider": fields.get("chain_provider", ""),
            "result": result, "notes": fields.get("status", ""), "source": source,
            "date": datetime.date.today().isoformat()}


def cell(text):
    return (text or "").replace("|", "\\|").replace("\n", " ")


def render(records):
    order = {r: i for i, r in enumerate(RESULTS)}
    records = sorted(records, key=lambda r: (r["game"].lower(), r["backend"], order.get(r["result"], 9), r["date"]))
    lines = ["<!-- Generated by tools/build_compat_matrix.py from docs/compat/compat.json. Edit the JSON, not this file. -->",
             "# Compatibility matrix", "",
             "One row per report. The same game can appear more than once: per backend, per GPU, per runtime version.",
             "A row from the README before 1.10.0 was tested on an RTX 40 unless its notes say otherwise.", "",
             f"{len(records)} reports; {sum(1 for r in records if r['result'] == 'Working')} working, "
             f"{sum(1 for r in records if r['result'] == 'Partially working')} partially, "
             f"{sum(1 for r in records if r['result'] == 'Not working')} not working.", "",
             "| Game | Backend | API | GPU | Streamline | Frame generation file | Result | Notes | Source | Date |",
             "|---|---|---|---|---|---|---|---|---|---|"]
    for r in records:
        lines.append("| " + " | ".join(cell(r.get(f, "")) for f in ["game", "backend", "api", "gpu", "streamline", "provider",
                                                                     "result", "notes", "source", "date"]) + " |")
    return "\n".join(lines) + "\n"


def main():
    args = sys.argv[1:]
    records = load()
    if "--import-readme" in args:
        imported = import_readme()
        keep = [r for r in records if r["source"] != "README (before 1.10.0)"]
        records = imported + keep
        save(records)
        print(f"imported {len(imported)} README rows; {len(keep)} other records kept")
    if "--from-report" in args:
        get = lambda name: args[args.index(name) + 1]
        record = from_report(get("--from-report"), get("--game"), get("--result"), get("--source"))
        if record["result"] not in RESULTS:
            sys.exit(f"result must be one of {RESULTS}")
        records.append(record)
        save(records)
        print("added", record["game"], record["backend"], record["result"])
    for r in records:
        if r["result"] not in RESULTS:
            sys.exit(f"{r['game']}: unknown result {r['result']}")
    text = render(records)
    if "--check" in args:
        if not os.path.exists(MATRIX) or open(MATRIX, encoding="utf-8").read() != text:
            sys.exit("docs/compat/matrix.md is stale: run tools/build_compat_matrix.py")
        print(f"PASS: {len(records)} records, matrix.md current")
        return
    open(MATRIX, "w", encoding="utf-8", newline="\n").write(text)
    print(f"wrote docs/compat/matrix.md ({len(records)} records)")


main()
