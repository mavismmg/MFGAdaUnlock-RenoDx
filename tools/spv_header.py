# 1.12.0 (DLSS 5, phase E): SPIR-V files to a C++ header of uint32_t arrays.
# usage: spv_header.py <out.h> <name>=<file.spv> ...
import sys
out = [ '// Generated by tools/spv_header.py: neural rendering\'s Vulkan passes (nr_vulkan.hlsl).', '#pragma once', '#include <cstdint>' ]
for arg in sys.argv[2:]:
    name, path = arg.split('=', 1)
    data = open(path, 'rb').read()
    words = [int.from_bytes(data[i:i + 4], 'little') for i in range(0, len(data), 4)]
    out.append('inline constexpr uint32_t %s[] = {' % name)
    for i in range(0, len(words), 8):
        out.append('  ' + ', '.join('0x%08x' % w for w in words[i:i + 8]) + ',')
    out.append('};')
open(sys.argv[1], 'w').write('\n'.join(out) + '\n')
